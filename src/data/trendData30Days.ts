/**
 * Synchronizes the 30-day trend with current live application state
 * so that the most recent day accurately reflects real-time telemetry.
 */
export function getSynchronized30DayTrend(
  currentCropHealth?: number,
  currentPestSeverity?: number
): CropPestHistoricalTrendPoint[] {
  const points = [...HISTORICAL_30_DAY_TREND_POINTS];
  const lastIndex = points.length - 1;

  if (lastIndex >= 0) {
    const lastPoint = { ...points[lastIndex] };
    if (typeof currentCropHealth === 'number') {
      lastPoint.cropHealthScore = Math.min(100, Math.max(0, currentCropHealth));
    }
    if (typeof currentPestSeverity === 'number') {
      lastPoint.pestSeverityIndex = Math.min(100, Math.max(0, currentPestSeverity));
    }
    points[lastIndex] = lastPoint;
  }

  return points;
}
